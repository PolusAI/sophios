def run_cwl_local(workflow_name: str, cwl_runner: str, docker_cmd: str, use_subprocess: bool) -> int:
    """Run compiled CWL output (stem `workflow_name` in ``autogenerated/``) with `cwl_runner` and container engine
    `docker_cmd`; return the exit code."""
    quiet = ["--quiet"]
    skip_schemas = ["--skip-schemas"]
    provenance = ["--provenance", f"provenance/{workflow_name}"]
    docker_cmd_: list[str] = []
    if docker_cmd == "docker":
        docker_cmd_ = []
    elif docker_cmd == "singularity":
        docker_cmd_ = ["--singularity"]
    else:
        docker_cmd_ = ["--user-space-docker-cmd", docker_cmd]
    write_summary = ["--write-summary", f"output_{workflow_name}.json"]
    path_check = ["--relax-path-checks"]
    docker_pull = ["--disable-pull"]
    # Its images come from cwl-docker-extract, as every other run's do, not from the run.
    preflight.prepare([Path(f"autogenerated/{workflow_name}.cwl")],
                      preflight.RunSettings(docker_cmd, str(Path.cwd())))
    script = "cwltool_filterlog" if cwl_runner == "cwltool" else cwl_runner
    cmd = [script] + docker_pull + quiet + provenance + \
        docker_cmd_ + write_summary + skip_schemas + path_check
    if cwl_runner == "cwltool":
        cmd += [
            "--leave-outputs",
            f"autogenerated/{workflow_name}.cwl",
            f"autogenerated/{workflow_name}_inputs.yml",
        ]
    elif cwl_runner == "toil-cwl-runner":
        cmd += [
            "--outdir",
            "outdir_toil",
            "--jobStore",
            f"file:./jobStore_{workflow_name}",
            "--clean",
            "always",
            f"autogenerated/{workflow_name}.cwl",
            f"autogenerated/{workflow_name}_inputs.yml",
        ]

    retval = 1
    print("Running " + " ".join(cmd))
    if use_subprocess:
        proc = sub.run(cmd, check=False)
        retval = proc.returncode
    else:
        print("via cwltool.main.main python API")
        try:
            if cwl_runner == "cwltool":
                retval = cwltool.main.main(cmd[1:])
            elif cwl_runner == "toil-cwl-runner":
                retval = toil.cwl.cwltoil.main(cmd[1:])
            else:
                raise Exception("Invalid cwl_runner!")

            print(
                f"Final output json metadata blob is in output_{workflow_name}.json")
        except Exception as exc:  # pylint: disable=W0718:broad-exception-caught
            print("Failed to execute", workflow_name)
            print(
                f"See error_{workflow_name}.txt for detailed technical information.")
            with open(f"error_{workflow_name}.txt", mode="w", encoding="utf-8") as f:
                traceback.print_exception(
                    type(exc), value=exc, tb=None, file=f)
            print(exc)
    return retval


def write_out_to_disk(res: Json, workflow_name: str) -> None:
    """Write compiled REST output `res` to disk as `workflow_name` before invoking a CWL runner."""
    res_cwl = copy.deepcopy(res)
    res_cwl.pop("retval", None)
    res_cwl.pop("cwlJobInputs", None)
    res_cwl.pop("name", None)
    compiled_cwl = workflow_name + ".cwl"
    inputs_yml = workflow_name + "_inputs.yml"
    with open(Path.cwd() / "autogenerated" / compiled_cwl, "w", encoding="utf-8") as f:
        yaml.dump(res_cwl, f)
    with open(Path.cwd() / "autogenerated" / inputs_yml, "w", encoding="utf-8") as f:
        yaml.dump(res["cwlJobInputs"], f)


def prepare_call_rest_api(inp_path: Path) -> Json:
    """Load a REST payload fixture and compile it through the REST API; return ``compile_wf``'s response."""
    with open(inp_path, "r", encoding="utf-8") as f:
        inp = json.load(f)
    scope = {"type": "http"}

    async def receive() -> Json:
        inp_byte = json.dumps(inp).encode("utf-8")
        return {"type": "http.request", "body": inp_byte}

    req: Request = Request(scope)
    req._receive = receive
    return asyncio.run(api.compile_wf(req))


@pytest.mark.skip_pypi_ci
@pytest.mark.parametrize(
    "inp_file",
    [
        "single_node.json",
        "single_node_bbbc_download.json",
        "bbbc_download_wfb.json",
        "multi_node.json",
        "multi_node_inline_cwl.json",
    ],
)
def test_rest_core_runs_workflow(inp_file: str) -> None:
    """Compile representative REST payloads and run the resulting workflows.

    Args:
        inp_file (str): Fixture filename under ``tests/contrib/rest_wfb_objects``.
    """
    inp_path = REST_OBJECTS / inp_file
    workflow_name = inp_file.split(".", maxsplit=1)[0]
    res = prepare_call_rest_api(inp_path)
    write_out_to_disk(res, workflow_name)
    retval = run_cwl_local(workflow_name, "cwltool", "docker", False)
    assert retval == 0


#: A WFB setting: text, often what YAML would read as something else, or any JSON value holding it; but the empty
#: string, which `wfb_to_wic` leaves as it is.
_TEXT = st.lists(st.sampled_from(' \t#:-[]{},&*!|>\'"%@`') | st.text(max_size=3), min_size=1).map(''.join).filter(bool)
_SETTINGS = _TEXT | st.recursive(st.none() | st.booleans() | st.integers() | st.floats(allow_nan=False) | _TEXT,
                                 lambda inner: st.lists(inner, max_size=3) | st.dictionaries(st.text(), inner,
                                                                                             max_size=3), max_leaves=6)


@budget(100)
@given(st.dictionaries(st.text(min_size=1), _SETTINGS, max_size=5))
@example({'glob': '*.tif', 'layout': '{row:c}', 'note': 'x # y', 'count': '5', 'flag': 'true', 'indices': '[1, 2]',
          'none': None, 'size': 5, 'numbers': [1, 2]})
def test_wfb_to_wic_keeps_settings_as_sent(settings: Json) -> None:
    """A WFB setting reaches the inline input as sent, not re-read as YAML."""
    payload = {'nodes': [{'id': 1, 'pluginId': 'touch', 'settings': {'inputs': settings}}], 'links': []}
    wic = wfb_to_wic(payload, [])
    assert wic['steps'][0]['in'] == {k: {Key.INLINE_INPUT: v} for k, v in settings.items()}


def _payload(name: str) -> Json:
    """The payload `name` names: a file of rest_wfb_objects, or `<payload>+<addition>`, the payload with the node and
    link of the addition added."""
    payload, *additions = name.split('+')
    loaded: Json = json.loads((REST_OBJECTS / payload).read_text(encoding='utf-8'))
    for addition in additions:
        added = json.loads((REST_OBJECTS / addition).read_text(encoding='utf-8'))
        loaded['state']['nodes'].append(added['node'])
        loaded['state']['links'].append(added['link'])
    return loaded


def test_rest_compiles_each_payload_to_what_it_states(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                                                      capsys: pytest.CaptureFixture[str]) -> None:
    """Each payload of rest_wfb_objects/expected.yaml compiles, in a directory holding s.sh, to the steps it states,
    and says what it states; each input a WFB payload's edge feeds is filled with the output that feeds it."""
    shutil.copyfile(REST_OBJECTS / 's.sh', tmp_path / 's.sh')
    monkeypatch.chdir(tmp_path)
    for name, stated in yaml.safe_load((REST_OBJECTS / 'expected.yaml').read_text(encoding='utf-8')).items():
        payload = tmp_path / 'payload.json'
        payload.write_text(json.dumps(_payload(name)), encoding='utf-8')
        capsys.readouterr()
        res = prepare_call_rest_api(payload)
        assert int(res['retval']) == 0, name
        assert match(stated['steps'], res['steps']), (name, res['steps'])
        assert stated.get('said', '') in capsys.readouterr().err, name
        if 'filled' in stated:
            wfb = _payload(name)
            expected = copy.deepcopy(wfb)
            for node, inputs in stated['filled'].items():
                expected['state']['nodes'][node]['settings']['inputs'].update(inputs)
            assert update_payload_missing_inputs_outputs(wfb) == expected
