"""A run on Windows stops at the pre-flight with one diagnostic, before anything starts, and a compute service is
refused with one too.

cwltool and Toil import `pwd`, which Windows does not have, so no runner runs there; nor can Python there open the
Unix socket the compute client reaches its service over. These tests run on the Windows leg, against the platform
itself.
"""
import sys
import asyncio
from pathlib import Path

import pytest

from sophios import compute
from sophios import main as cli
from sophios import preflight
from sophios.api.python.workflow import Step, Workflow
from sophios.lang import SophiosError

REPO_ROOT = Path(__file__).resolve().parents[2]
WINDOWS = 'cwltool and Toil need the pwd module, which Windows does not have'

pytestmark = pytest.mark.skipif(sys.platform != 'win32', reason='checks Windows itself')


@pytest.fixture(autouse=True)
def _in_tmp_path(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.chdir(tmp_path)


def _echo() -> Workflow:
    echo = Step(clt_path=REPO_ROOT / 'cwl_adapters' / 'echo.cwl')
    echo.inputs.message = 'hello'
    return Workflow([echo], 'wf')


def _refused(runner: str) -> str:
    return f'error [wic029] {runner} cannot run here ({WINDOWS}): run Sophios inside WSL'


@pytest.mark.fast
def test_the_platform_says_why_no_runner_runs() -> None:
    assert preflight.PLATFORM_LACKS_RUNNERS == WINDOWS


@pytest.mark.fast
@pytest.mark.parametrize('runner', ['cwltool', 'toil-cwl-runner'])
def test_run_local_says_to_run_in_wsl(runner: str, monkeypatch: pytest.MonkeyPatch,
                                      capsys: pytest.CaptureFixture[str]) -> None:
    helloworld = REPO_ROOT / 'docs' / 'tutorials' / 'helloworld.wic'
    monkeypatch.setattr('sys.argv', ['sophios', '--yaml', str(helloworld), '--run_local', '--cwl_runner', runner])
    with pytest.raises(SystemExit) as caught:
        cli.main()
    assert caught.value.code == 1
    assert _refused(runner) in capsys.readouterr().err


@pytest.mark.fast
def test_workflow_run_raises_it(tmp_path: Path) -> None:
    with pytest.raises(SophiosError) as caught:
        _echo().run(basepath=str(tmp_path / 'autogenerated'))
    assert any(str(diagnostic).startswith(_refused('cwltool')) for diagnostic in caught.value.diagnostics)


@pytest.mark.fast
def test_workflow_start_raises_it(tmp_path: Path) -> None:
    with pytest.raises(SophiosError) as caught:
        _echo().start(basepath=str(tmp_path / 'autogenerated'))
    assert any(str(diagnostic).startswith(_refused('cwltool')) for diagnostic in caught.value.diagnostics)


@pytest.mark.fast
def test_workflow_run_async_raises_it(tmp_path: Path) -> None:
    with pytest.raises(SophiosError) as caught:
        asyncio.run(_echo().run_async(basepath=str(tmp_path / 'autogenerated')))
    assert any(str(diagnostic).startswith(_refused('cwltool')) for diagnostic in caught.value.diagnostics)


@pytest.mark.fast
@pytest.mark.parametrize('url', ['ssh://cluster', 'unix:///api.sock', 'http://cluster:7998'])
def test_a_compute_service_says_to_run_in_wsl(url: str) -> None:
    with pytest.raises(compute.ServiceUnavailable) as unavailable:
        compute.Service(url)
    assert unavailable.value.messages == (
        'the compute client needs macOS, Linux or WSL: it reaches the service over a Unix socket, which Python on '
        'Windows itself cannot open; run Sophios inside WSL',)
