"""The discovery config: a file the user names is only read; the default is generated once."""
import json
import shutil
from pathlib import Path

import pytest

from sophios import input_output as io

from .cases import DATA
from .helpers import run_cli


@pytest.mark.fast
def test_an_explicit_config_file_is_only_read(monkeypatch: pytest.MonkeyPatch, tmp_path: Path,
                                              capsys: pytest.CaptureFixture[str]) -> None:
    """An explicit config keeps its path semantics, relative to the working directory, and creates no default
    installation, nor anything it names. One that does not exist is a usage error naming it: a typo in --config_file
    used to write a fresh default config over the user's own. A search path given as a string is a type error naming
    its key, not iterated into characters."""
    monkeypatch.setenv('HOME', str(tmp_path))
    monkeypatch.chdir(tmp_path)
    users_config = tmp_path / 'wic' / 'global_config.json'
    users_config.parent.mkdir()
    users_config.write_text('{"mine": true}', encoding='utf-8')
    shutil.copy(DATA / 'config' / 'w.wic', tmp_path / 'w.wic')
    assert run_cli(monkeypatch, '--yaml', 'w.wic', '--generate_cwl_workflow',
                   '--homedir', tmp_path, '--config_file', 'typo.json') == 2
    assert 'typo.json' in capsys.readouterr().err
    assert users_config.read_text(encoding='utf-8') == '{"mine": true}'

    config_file = tmp_path / 'config' / 'custom.json'
    absolute_examples = tmp_path / 'absolute-examples'
    io.write_config_to_disk({'search_paths_cwl': {'global': ['relative-adapters']},
                             'search_paths_wic': {'global': [str(absolute_examples)]}}, config_file)
    before = config_file.read_bytes()
    config = io.get_config(config_file, tmp_path / 'unused-home')
    assert config['search_paths_cwl']['global'] == [str(tmp_path / 'relative-adapters')]
    assert config['search_paths_wic']['global'] == [str(absolute_examples)]
    assert config_file.read_bytes() == before
    assert not [path for path in (tmp_path / 'unused-home', tmp_path / 'relative-adapters', absolute_examples)
                if path.exists()]
    for tag in ('search_paths_cwl', 'search_paths_wic'):
        config_file.write_text(json.dumps({'search_paths_cwl': {'global': []}, 'search_paths_wic': {'global': []},
                                           tag: {'global': '/whole/disk'}}), encoding='utf-8')
        with pytest.raises(TypeError, match=f'{tag}.global'):
            io.read_config_from_disk(config_file)


@pytest.mark.fast
@pytest.mark.parametrize('generate_explicitly,relative_homedir', [(False, True), (True, False)],
                         ids=['first-use-relative-home', 'generate-config-absolute-home'])
def test_selected_home_is_provisioned_once_without_touching_an_existing_installation(
        monkeypatch: pytest.MonkeyPatch, tmp_path: Path,
        generate_explicitly: bool, relative_homedir: bool) -> None:
    """Both CLI entry points provision --homedir; subsequent reads preserve the user's edits."""
    process_home = tmp_path / 'process-home'
    monkeypatch.setattr(Path, 'home', classmethod(lambda cls: process_home))
    monkeypatch.chdir(tmp_path)
    io.get_config(None, process_home)
    before = {path.relative_to(process_home): path.read_bytes()
              for path in process_home.rglob('*') if path.is_file()}
    homedir = Path('selected-home') if relative_homedir else tmp_path / 'selected-home'
    if generate_explicitly:
        assert run_cli(monkeypatch, '--homedir', homedir, '--generate_config') == 0
    else:
        shutil.copy(DATA / 'config' / 'w.wic', tmp_path / 'w.wic')
        assert run_cli(monkeypatch, '--homedir', homedir, '--yaml', 'w.wic', '--generate_cwl_workflow') is None
        assert (tmp_path / 'autogenerated' / 'w.cwl').is_file()

    config = io.read_config_from_disk(io.default_config_file(homedir))
    adapters = homedir.absolute() / 'wic' / 'cwl_adapters'
    examples = homedir.absolute() / 'wic' / 'examples'
    assert config['search_paths_cwl']['global'] == [str(adapters)]
    assert config['search_paths_wic']['global'] == [str(examples)]
    assert (adapters / 'touch.cwl').is_file()
    assert any(examples.rglob('*.wic'))

    default = io.default_config_file(homedir)
    default.write_text('{"search_paths_cwl": {}, "search_paths_wic": {}}', encoding='utf-8')
    assert io.get_config(None, homedir) == {'search_paths_cwl': {}, 'search_paths_wic': {}}
    assert {path.relative_to(process_home): path.read_bytes()
            for path in process_home.rglob('*') if path.is_file()} == before
