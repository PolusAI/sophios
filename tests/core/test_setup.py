@dataclass(frozen=True, slots=True)
class CorpusRegistry:
    """The explicit environment-dependent inputs used by corpus tests."""

    tools: Tools
    workflows: dict[str, dict[str, Path]]
    validator: Draft202012Validator
    #: The store the validator was built from, carrying a schema per tool and
    #: per compiled workflow. `wic_main_schema(hypothesis=True)` inlines from
    #: it, because hypothesis-jsonschema will not resolve an external `$ref`.
    schema_store: dict[str, Json]


def _config() -> tuple[Json, bool]:
    """Read configuration without provisioning a missing user config."""
    args = sophios.cli.get_args()
    if Path(args.config_file).exists():
        return io.get_config(Path(args.config_file), Path(args.config_file)), args.quiet
    return io.get_basic_config(), args.quiet


@lru_cache(maxsize=1)
def workflow_paths() -> dict[str, dict[str, Path]]:
    """Discover workflow source paths without loading any process plugins."""
    config, _ = _config()
    paths: dict[str, dict[str, Path]] = sophios.plugins.get_yml_paths(config)
    return paths


def yml_path_is_workflow(yml_path: Path) -> bool:
    """Return whether a `.wic` file looks like a compilable workflow root.

    Args:
        yml_path (Path): Path to a workflow-definition file.

    Returns:
        bool: True when the file declares steps or workflow implementations.
    """
    with open(yml_path, mode='r', encoding='utf-8') as yml_file:
        yml = yaml.load(yml_file.read(), Loader=wic_loader())
    if not isinstance(yml, dict):
        return False
    wic_tag = yml.get('wic', {})
    document_shaped = (
        'steps' in yml
        or 'implementations' in yml
        or (isinstance(wic_tag, dict) and 'implementations' in wic_tag)
    )
    anchors = _tag_values(yml, 'wic_anchor')
    aliases = _tag_values(yml, 'wic_alias')
    has_child = _has_workflow_call(yml)
    return document_shaped and (aliases <= anchors or has_child)


def _tag_values(value: object, key: str) -> set[str]:
    """Collect desugared edge names without importing compiler semantics."""
    if isinstance(value, dict):
        found = {str(value[key])} if key in value else set()
        return found | set().union(
            *(_tag_values(item, key) for item in value.values()), set())
    if isinstance(value, list):
        return set().union(*(_tag_values(item, key) for item in value), set())
    return set()


def _has_workflow_call(value: object) -> bool:
    if isinstance(value, dict):
        if isinstance(value.get('id'), str) and value['id'].endswith('.wic'):
            return True
        return any(_has_workflow_call(item) for item in value.values())
    if isinstance(value, list):
        return any(_has_workflow_call(item) for item in value)
    return False


SCHEMA_STORE_PATH = Path('autogenerated/schemas/schema_store.json')


def _cached_schema_store(workflows: dict[str, dict[str, Path]]) -> dict[str, Json]:
    """The store ``sophios --generate_schemas`` wrote, when it covers the corpus.

    Compiling a schema per workflow costs minutes on the real corpus, and every
    CI lane runs the generator before the pytest steps that need a registry, so
    rebuilding here pays that cost again in each worker process. A store missing
    any discovered workflow is stale and is discarded rather than patched.
    """
    if not SCHEMA_STORE_PATH.exists():
        return {}
    with open(SCHEMA_STORE_PATH, mode='r', encoding='utf-8') as f:
        store: dict[str, Json] = json.load(f)
    expected = {f'workflows/{name}.json' for paths in workflows.values() for name in paths}
    return store if expected.issubset(store) else {}


@lru_cache(maxsize=1)
def load_test_registry() -> CorpusRegistry:
    """Load tools and schemas on first test execution, never at collection.

    Schema construction is in-memory.  Importing this module therefore cannot
    discover CWL plugins or write under ``autogenerated/``.
    """
    config, quiet = _config()
    tools = sophios.plugins.get_tools_cwl(config, quiet=quiet)
    workflows = workflow_paths()
    stems = sophios.utils.flatten([list(paths) for paths in workflows.values()])
    schema_store = _cached_schema_store(workflows)
    if not schema_store:
        args = sophios.cli.get_args()
        validator = sophios.schemas.wic_schema.get_validator(
            tools, stems, schema_store, write_to_disk=False)
        for workflow_name, workflow_path in (
                (name, path) for paths in workflows.values() for name, path in paths.items()):
            if not yml_path_is_workflow(workflow_path):
                continue
            schema = sophios.schemas.wic_schema.compile_workflow_generate_schema(
                args.homedir, workflow_name, workflow_path, tools, workflows, validator,
                args.ignore_validation_errors)
            schema_store[schema['$id']] = schema
    validator = sophios.schemas.wic_schema.get_validator(
        tools, stems, schema_store, write_to_disk=False)
    return CorpusRegistry(tools, workflows, validator, schema_store)


@pytest.fixture(scope='session')
def corpus_registry() -> CorpusRegistry:
    """Explicit registry fixture for tests that exercise the discovered corpus."""
    return load_test_registry()


def wic_yaml_filter_blank_steps(yml: Yaml) -> bool:
    """Filters out Yaml instances with blank steps.

    Args:
        yml (Yaml): A randomly generated Yaml instance.

    Returns:
        bool: True if there are no blank steps.
    """
    steps = yml.get('steps', [])
    if isinstance(steps, list):
        return not (
            steps == []
            or any(
                step == {}
                or not isinstance(step, dict)
                or not isinstance(step.get('id'), str)
                or step.get('id', '') == ''
                for step in steps
            )
        )
    if isinstance(steps, dict):
        return not (
            steps == {}
            or any(
                not isinstance(key, str) or key == ''
                for key in steps
            )
        )
    return bool(steps != [])


def wic_yaml_filter_top_level_types(yml: Yaml) -> bool:
    """Filters out obvious top-level type mismatches.

    Args:
        yml (Yaml): A randomly generated Yaml instance.

    Returns:
        bool: True if optional top-level fields use plausible container types.
    """
    namespaces = yml.get('$namespaces', {})
    schemas = yml.get('$schemas', [])
    namespaces_valid = namespaces is None or isinstance(namespaces, dict)
    schemas_valid = schemas is None or isinstance(schemas, list)
    return namespaces_valid and schemas_valid


def wic_yaml_filter_implementations_or_steps(yml: Yaml) -> bool:
    """Filters out Yaml instances with no implementations and no steps.

    Args:
        yml (Yaml): A randomly generated Yaml instance.

    Returns:
        bool: True if there is either implementations or steps (or both).
    """
    return ('implementations' in yml or 'steps' in yml)


@lru_cache(maxsize=1)
def wic_strategy() -> SearchStrategy:
    """The schema strategy, built once from the loaded registry.

    Built from the registry's own `schema_store`, not an empty one: with no
    store, every step is an unresolved `{"$ref": "tools/<stem>.json"}` and
    hypothesis-jsonschema draws nothing at all, because it does not fetch
    remote references.

    Cached because the caller draws through `st.data()`, so an uncached build
    would re-derive the schema once per example rather than once per session.
    """
    registry = load_test_registry()
    stems = sophios.utils.flatten([list(paths) for paths in registry.workflows.values()])
    schema = sophios.schemas.wic_schema.wic_main_schema(
        registry.tools, stems, registry.schema_store, hypothesis=True)
    strategy = cast(SearchStrategy[Yaml], hj.from_schema(schema))
    strategy = strategy.filter(wic_yaml_filter_blank_steps)
    strategy = strategy.filter(wic_yaml_filter_implementations_or_steps)
    return strategy.filter(wic_yaml_filter_top_level_types)


def test_version_resolution_warns_when_package_metadata_is_missing(monkeypatch: pytest.MonkeyPatch) -> None:
    """An uninstalled package warns rather than resolving to a wrong version."""
    def missing_version(distribution_name: str) -> str:
        raise PackageNotFoundError(distribution_name)

    monkeypatch.setattr(sophios, "version", missing_version)

    with pytest.warns(RuntimeWarning, match="sophios is not installed"):
        assert sophios._resolve_version() == "unknown"
