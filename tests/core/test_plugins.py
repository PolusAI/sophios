@pytest.mark.fast
def test_partial_failure_and_entrypoint_removal_write_what_their_example_states(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]) -> None:
    """Each run of tests/core/data/partial_failure/expected.yaml, compiled by the command line with its flags; the
    images under --docker_remove_entrypoints are built after the pre-flight pulls the originals, so the CWL the runner
    reads names the built ones."""
    project = tmp_path / 'project'
    shutil.copytree(DATA / 'partial_failure', project, ignore=shutil.ignore_patterns('expected.yaml'))
    # file_watchers holds cwl_subinterpreter, the step a real-time analysis is declared with.
    search_config(project / 'config.json', [project, ADAPTERS / 'file_watchers'], [project])
    monkeypatch.setattr(sophios.preflight, 'prepare', lambda *_a, **_k: None)
    monkeypatch.setattr(sophios.post_compile.docker, 'from_env', _no_images)
    monkeypatch.chdir(project)
    for run in yaml.safe_load((DATA / 'partial_failure' / 'expected.yaml').read_text(encoding='utf-8')):
        shutil.rmtree(project / 'autogenerated', ignore_errors=True)
        code = run_cli(monkeypatch, '--yaml', 'w.wic', '--config_file', 'config.json', *run['flags'])
        if 'refused' in run:
            assert code == 2 and run['refused'] in capsys.readouterr().err, run['why']
            continue
        assert code is None, run['why']
        for path, expected in run['written'].items():
            written = yaml.safe_load((project / 'autogenerated' / path).read_text(encoding='utf-8'))
            assert match(expected, written), (run['why'], path, written)


#: An output's type in each form CWL writes one: one string, with `?` or `[]` or neither, a union with or without
#: null, a type written in full, and the two streams.
_OUTPUT_TYPES: Final = st.sampled_from([
    'File', 'string', 'File[]', 'File?', ['File', 'Directory'], ['null', 'File'], ['File?', 'string'],
    {'type': 'array', 'items': 'File'}, {'type': 'enum', 'symbols': ['a', 'b']},
    {'type': 'record', 'fields': {'f': {'type': 'File', 'outputBinding': {'glob': 'f'}}}}, 'stdout', 'stderr'])
_STREAMS: Final = ('stdout', 'stderr')


def _output(declared: Any, alone: bool, bound: bool = False) -> Any:
    """An output of type `declared`: the type alone, where CWL lets it stand for the output, or a mapping, which a
    stream's holds no binding in unless `bound`, which CWL refuses."""
    if alone and not isinstance(declared, dict):
        return declared
    binding = {} if declared in _STREAMS and not bound else {'outputBinding': {'glob': 'out'}}
    return {'type': declared, 'doc': 'kept', **binding}


@st.composite
def _tools(draw: st.DrawFn) -> Yaml:
    """A tool whose outputs are of any form, as a mapping or as the list a packed tool writes, or that has none, and
    that may name its streams and its own success codes."""
    outputs = draw(st.dictionaries(st.sampled_from(['a', 'b', 'c']),
                                   st.tuples(_OUTPUT_TYPES, st.booleans(), st.booleans()), max_size=3))
    listed = draw(st.booleans())
    tool: Yaml = {'cwlVersion': CWL_VERSION, 'class': draw(st.sampled_from(['CommandLineTool', 'ExpressionTool'])),
                  'inputs': {}, 'outputs': [{'id': name, **_output(declared, False, bound)}
                                            for name, (declared, _, bound) in outputs.items()] if listed else
                  {name: _output(declared, alone, bound) for name, (declared, alone, bound) in outputs.items()}}
    if not outputs and draw(st.booleans()):
        del tool['outputs']
    for stream in _STREAMS:
        if draw(st.booleans()):
            tool[stream] = f'{stream}.txt'
    own = draw(st.none() | st.lists(st.integers(0, 9), max_size=3))
    return tool if own is None else {**tool, 'successCodes': own}


def _declared(outputs: Any) -> list[tuple[str, Yaml]]:
    """Each output's name and mapping, from either form; a type alone as `{type: ...}`."""
    if isinstance(outputs, list):
        return [(entry['id'], {key: value for key, value in entry.items() if key != 'id'}) for entry in outputs]
    return [(name, entry if isinstance(entry, dict) else {'type': entry}) for name, entry in outputs.items()]


def _admits(declared: Any) -> list[Any]:
    """What a port of type `declared` admits besides null, as the IR reads the type."""
    canonical = PortType(declared).canonical
    return [member for member in (canonical if isinstance(canonical, list) else [canonical]) if member != 'null']


def _clt(outputs: Any, **fields: Any) -> Yaml:
    return {'cwlVersion': CWL_VERSION, 'class': 'CommandLineTool', 'inputs': {},
            **({} if outputs is None else {'outputs': outputs}), **fields}


@pytest.mark.fast
@given(_tools(), st.lists(st.integers(0, 255), max_size=4), st.booleans())
@example(_clt([{'id': 'o', 'type': 'File', 'outputBinding': {'glob': 'o'}}]), [1], True)
@example(_clt({'out': {'type': 'stdout'}, 'err': {'type': 'stderr'}}), [1], True)
@example(_clt(None), [1], True)
@example(_clt({'said': {'type': 'stdout', 'outputBinding': {'glob': 'said.txt'}}}), [1], True)
@budget(100)
def test_under_partial_failure_every_output_of_a_tool_accepts_null(tool: Yaml, codes: list[int],
                                                                   enabled: bool) -> None:
    """Under partial failure each output of a CommandLineTool accepts null, in whichever form it is written, and admits
    what it admitted; a stream is a `File?` globbing the file the tool names, or one the tool is given, each stream its
    own, and a stream output with a binding of its own, which is no CWL, is left as it is. The tool's success codes
    join the policy's. Nothing else changes, a tool with no outputs gains none, a tool already tolerant stays as it is,
    and without partial failure, or for any other class, nothing changes at all."""
    policy = RunPolicy(enabled, tuple(codes))
    written = tolerant_tool(copy.deepcopy(tool), policy)
    if not enabled or tool['class'] != 'CommandLineTool':
        assert written == tool
        return
    assert written['successCodes'] == sorted({0, *codes, *tool.get('successCodes', [])})
    assert ('outputs' in written) == ('outputs' in tool)
    assert isinstance(written.get('outputs'), list) == isinstance(tool.get('outputs'), list)
    declared = _declared(tool.get('outputs', {}))
    assert [name for name, _ in _declared(written.get('outputs', {}))] == [name for name, _ in declared]
    for (_, before), (_, after) in zip(declared, _declared(written.get('outputs', {}))):
        if before['type'] in _STREAMS and 'outputBinding' in before:
            assert after == before
        elif before['type'] in _STREAMS:
            assert after == {**before, 'type': 'File?', 'outputBinding': {'glob': written[before['type']]}}
        else:
            assert PortType(after['type']).optional and _admits(after['type']) == _admits(before['type'])
            assert {**after, 'type': None} == {**before, 'type': None}
    captured = [before['type'] for _, before in declared
                if before['type'] in _STREAMS and 'outputBinding' not in before]
    for stream in _STREAMS:
        if stream in tool:
            assert written[stream] == tool[stream]
        else:
            assert (stream in written) == (stream in captured)
            assert stream not in written or re.fullmatch('[0-9a-f]{40}', written[stream])
    if all(stream in written for stream in _STREAMS):
        assert written['stdout'] != written['stderr']
    unchanged = ('successCodes', 'outputs', *_STREAMS)
    assert {key: value for key, value in written.items() if key not in unchanged} == \
        {key: value for key, value in tool.items() if key not in unchanged}
    assert tolerant_tool(copy.deepcopy(written), policy) == written


def _section(before: list[Yaml], fields: Yaml | None, after: list[Yaml], mapping: bool) -> Yaml | list[Yaml]:
    """A `requirements` or `hints` holding `before`, a `DockerRequirement` of `fields` unless they are None, and
    `after`: a mapping keyed by class (hand-written adapters) or a list of `{class: ...}` entries (cwl_utils)."""
    entries = [*before, *([] if fields is None else [{'class': 'DockerRequirement', **fields}]), *after]
    if mapping:
        return {entry['class']: {k: v for k, v in entry.items() if k != 'class'} for entry in entries}
    return entries


def _tool(sections: Yaml) -> Yaml:
    return {'class': 'CommandLineTool', 'baseCommand': 'true', 'inputs': {}, 'outputs': {}, **sections}


def _workflow(runs: list[Any], mapping: bool, sections: Yaml) -> Yaml:
    """A workflow running each of `runs`, an embedded process or a file, its steps a mapping or a list."""
    steps = [{'id': f's{i}', 'in': {}, 'out': [], 'run': run} for i, run in enumerate(runs)]
    return {'class': 'Workflow', 'inputs': {}, 'outputs': {}, **sections,
            'steps': {step.pop('id'): step for step in steps} if mapping else steps}


def _pulls(section: str, image: str, mapping: bool = True) -> Yaml:
    return _tool({section: _section([], {'dockerPull': image}, [], mapping)})


#: Image references: a registry, with a port or none, 1 to 3 path segments, a tag or none, and a digest or none.
_IMAGES = st.from_regex(r'((docker\.io|localhost:5000|ghcr\.io)/)?([a-z0-9]+([._-][a-z0-9]+)?/){0,2}[a-z0-9]+'
                        r'(:[A-Za-z0-9_][A-Za-z0-9_.-]{0,9})?(@sha256:8{64})?', fullmatch=True)
#: Requirements beside a `DockerRequirement`, which may itself name no image to pull.
_OTHERS = st.lists(st.sampled_from([{'class': 'InlineJavascriptRequirement'},
                                    {'class': 'ResourceRequirement', 'ramMin': 64}]), max_size=2)
_DOCKER = st.one_of(st.none(), st.just({'dockerImageId': 'local'}), _IMAGES.map(lambda image: {'dockerPull': image}))
_SECTIONS = st.dictionaries(st.sampled_from(['requirements', 'hints']),
                            st.builds(_section, _OTHERS, _DOCKER, _OTHERS, st.booleans()))
_PROCESSES = st.recursive(_SECTIONS.map(_tool), lambda processes: st.builds(
    _workflow, st.lists(st.one_of(processes, st.just('elsewhere.cwl')), min_size=1, max_size=3), st.booleans(),
    _SECTIONS), max_leaves=6)


def _tagged(document: Any) -> Any:
    """`document` with each `dockerPull` at any depth tagged as docker-py's own parser reads its image."""
    if isinstance(document, list):
        return [_tagged(value) for value in document]
    if not isinstance(document, dict):
        return document
    tagged = {key: _tagged(value) for key, value in document.items()}
    if 'dockerPull' in document and '@' not in document['dockerPull']:
        repo, tag = sophios.post_compile.docker.utils.parse_repository_tag(  # type: ignore[attr-defined]
            document['dockerPull'])
        tagged['dockerPull'] = f"{repo}:{tag or 'latest'}-noentrypoint"
    return tagged


_DIGEST = 'polusai/openfold-tool@sha256:' + '8' * 64


@pytest.mark.fast
@budget(100)
@given(_PROCESSES)
@example(_pulls('requirements', 'docker.io/bash:4.4'))
@example(_pulls('requirements', 'docker.io/bash:4.4', mapping=False))
@example(_pulls('hints', 'localhost:5000/tools/bash:4.4'))
@example(_pulls('hints', 'localhost:5000/tools/bash:4.4', mapping=False))
@example(_pulls('requirements', _DIGEST))
@example(_pulls('hints', _DIGEST))
@example(_workflow([_pulls('requirements', 'docker.io/bash:4.4'),
                    _workflow([_pulls('hints', 'bash:5')], True, {}), 'elsewhere.cwl'], False, {}))
def test_every_image_the_runner_pulls_gets_the_noentrypoint_tag(document: Yaml) -> None:
    """Under `--docker_remove_entrypoints` each `dockerPull` the runner reads, in `requirements` (which cwl_utils
    renders as a list, and hand-written adapters as a mapping) or in `hints` (cwltool runs the image a hint names),
    of the document and of each tool embedded in its steps, at any depth (as `--cwl_inline_runtag` and
    `Workflow.run()` give the runner one), names the tag built; an image pulled by digest has no tag and no
    -noentrypoint build, so appending to it would make an invalid reference. Tagging twice is tagging once, and the
    document given is not changed."""
    before = copy.deepcopy(document)
    updated = sophios.plugins.dockerPull_append_noentrypoint(document)
    assert document == before
    assert updated == _tagged(document)
    assert sophios.plugins.dockerPull_append_noentrypoint(updated) == updated


def _no_images() -> SimpleNamespace:
    """A docker client with no images, so `--docker_remove_entrypoints` builds nothing."""
    return SimpleNamespace(images=SimpleNamespace(list=lambda: []))


#: The file a case lays out under each of its `files`, by kind.
_LAID_OUT: Final = {'tool': DATA / 'discovery' / 'laid_out.cwl', 'workflow': DATA / 'discovery' / 'laid_out.wic'}

#: A warning `_warn_duplicates` prints, read back as its stem, namespace, count, files and the file used.
_WARNING = re.compile(r"Warning! (tool|workflow) '(.+)' in namespace '(.+)' is defined by (\d+) files:\n"
                      r"((?:  .+\n)+)Using (.+?): it is the last one found .*\nTo use another.*\n")

#: The filesystem's own listing.
_LISTED = glob.glob


def _listed_in_reverse(pattern: str, *, recursive: bool = False) -> list[str]:
    """A directory's entries in reverse, as some filesystems list them."""
    return sorted(_LISTED(pattern, recursive=recursive), reverse=True)


def _relative(path: str | Path, base: Path) -> str:
    return Path(os.path.relpath(path, base)).with_suffix('').as_posix()


def _found(kind: str, roots: dict[str, list[str]], base: Path) -> dict[str, dict[str, str]]:
    """The file each stem resolves to, by namespace, in the order discovery returns them."""
    if kind == 'workflow':
        return {ns: {stem: _relative(path, base) for stem, path in stems.items()}
                for ns, stems in sophios.plugins.get_yml_paths({'search_paths_wic': roots}).items()}
    found: dict[str, dict[str, str]] = {}
    for key, tool in sophios.plugins.get_tools_cwl({'search_paths_cwl': roots}).items():
        found.setdefault(key.plugin_ns, {})[key.stem] = _relative(tool.run_path, base)
    return found


def _warnings(err: str, base: Path, kind: str) -> list[list[Any]]:
    """Each warning on `err` as [namespace, stem, its files], which names `kind`, states their count and uses the last;
    `err` holds nothing else."""
    said = []
    for named_kind, stem, namespace, count, files, used in _WARNING.findall(err):
        named = [_relative(line[2:], base) for line in files.splitlines()]
        assert (named_kind, int(count), _relative(used, base)) == (kind, len(named), named[-1])
        said.append([namespace, stem, named])
    assert _WARNING.sub('', err) == ''
    return said


@pytest.mark.fast
def test_each_stem_resolves_to_the_last_file_found(tmp_path_factory: pytest.TempPathFactory,
                                                   monkeypatch: pytest.MonkeyPatch,
                                                   capsys: pytest.CaptureFixture[str]) -> None:
    """Each case of data/discovery (see its README), under the filesystem's own listing and under it reversed:
    discovery must not depend on it. A search path that holds no tool says so on stdout."""
    for case in (param.values[0] for param in cases('discovery', 'files', 'found', 'kinds', 'roots', 'warnings',
                                                    'links')):
        with monkeypatch.context() as listing_patches:
            _resolves(case, tmp_path_factory.mktemp('layout'), listing_patches, capsys)
    empty = tmp_path_factory.mktemp('empty')
    assert not sophios.plugins.get_tools_cwl({'search_paths_cwl': {'global': [str(empty)]}})
    assert f'No cwl files found in {empty}' in capsys.readouterr().out


def _resolves(case: Yaml, base: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]) -> None:
    """One discovery case, laid out in `base`: not a test's tmp_path, which holds the case id that biobb_md and
    _inputs read."""
    for link, target in case.get('links', {}).items():
        (base / link).symlink_to(base / target, target_is_directory=True)
    for kind in case.get('kinds', ['tool']):
        for name in case['files']:
            (base / name).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(_LAID_OUT[kind], base / f'{name}{_LAID_OUT[kind].suffix}')
        roots = {ns: [str(base / root) for root in paths] for ns, paths in case.get('roots', {'global': ['']}).items()}
        for listing in (_LISTED, _listed_in_reverse):
            monkeypatch.setattr(glob, 'glob', listing)
            found = _found(kind, roots, base)
            assert found == case['found'], case['id']
            if kind == 'tool':
                assert [list(stems) for stems in found.values()] == [list(stems) for stems in case['found'].values()]
            out, err = capsys.readouterr()
            assert out == ''
            assert _warnings(err, base, kind) == [[ns, stem, files] for ns, stems in case.get('warnings', {}).items()
                                                  for stem, files in stems.items()]
