"""`--basepath` and `Workflow.run(basepath=)` are one setting: where Sophios writes what it generates. The project is
tests/core/data/basepath: the tool `noop` and the workflow `w.wic` that calls it."""
import json
import shlex
import shutil
import sys
from pathlib import Path
from typing import Final

import pytest

import sophios.plugins
from sophios import run_local
from sophios.api.python.workflow import Step, Workflow

from .cases import DATA
from .helpers import EACH_RUNNER, no_preflight, run_cli, search_config

pytestmark = pytest.mark.package


@pytest.fixture(name='project')
def _project(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> Path:
    """A working directory holding a copy of the project and a config that searches it. Nothing is pulled, and the
    runner command is captured instead of written."""
    root = tmp_path / 'project'
    shutil.copytree(DATA / 'basepath', root)
    search_config(root / 'config.json', [root], [root])
    no_preflight(monkeypatch)
    monkeypatch.chdir(root)
    return root


def _sophios(monkeypatch: pytest.MonkeyPatch, *flags: str) -> None:
    """`sophios --yaml w.wic --config_file config.json <flags>`, from the working directory."""
    assert run_cli(monkeypatch, '--yaml', 'w.wic', '--config_file', 'config.json', *flags) is None


def _files(base: Path) -> set[str]:
    return {path.relative_to(base).as_posix() for path in base.rglob('*') if path.is_file()}


#: Stands in for Graphviz's `dot`: `-Tsvg -o <file>` writes the drawing source it reads on stdin to <file>.
FAKE_DOT: Final = '''#!{python}
import sys
if '-Tsvg' in sys.argv:
    with open(sys.argv[sys.argv.index('-o') + 1], 'w', encoding='utf-8') as out:
        out.write(sys.stdin.read())
'''


@pytest.mark.fast
@pytest.mark.parametrize(('flags', 'written'), [
    (['--generate_cwl_workflow', '--basepath', 'out/generated'], {'w.cwl', 'w_inputs.yml'}),
    (['--generate_run_script', '--basepath', '{base}'], {'w.cwl', 'w_inputs.yml'}),
    (['--generate_cwl_workflow', '--graphviz', '--basepath', 'out/generated'], {'w.svg', 'w.wic.gv'}),
    (['--generate_schemas', '--basepath', 'out/generated'], {'schemas/wic.json'}),
], ids=['relative', 'absolute', 'drawings', 'schemas'])
def test_the_cli_writes_under_the_basepath_and_nowhere_else(project: Path, monkeypatch: pytest.MonkeyPatch,
                                                            flags: list[str], written: set[str]) -> None:
    """Under `--basepath`, relative to the working directory or absolute: the compiled workflow and job file; the run
    script names it for every path the run writes; the drawings, which need `dot` and nothing else of the environment,
    as cwltool runs through the interpreter that runs Sophios and draws the workflow this compile has written; and the
    schema, which is something Sophios generates. No `autogenerated/` appears."""
    base = project / 'out' / 'generated'
    cmdlines: list[str] = []
    monkeypatch.setattr(run_local, 'generate_run_script', cmdlines.append)
    if '--graphviz' in flags:
        if sys.platform == 'win32':
            pytest.skip('the stand-in for dot is a script with a shebang')
        (dot := project.parent / 'tools' / 'dot').parent.mkdir()
        dot.write_text(FAKE_DOT.format(python=sys.executable), encoding='utf-8')
        dot.chmod(0o755)
        monkeypatch.setenv('PATH', str(dot.parent))
    if '--generate_schemas' in flags:
        assert run_cli(monkeypatch, *flags) == 0
    else:
        _sophios(monkeypatch, *(flag.format(base=base) for flag in flags))
    assert written <= _files(base) and not (project / 'autogenerated').exists()
    if '--graphviz' in flags:
        drawn = (base / 'w.svg').read_text(encoding='utf-8')
        assert drawn.startswith('digraph') and 'Workflow Outputs' in drawn
    if '--generate_run_script' in flags:
        resolved = str(base.resolve())
        assert all(resolved in cmdline for cmdline in cmdlines) and len(cmdlines) == 1
        assert f'--provenance {shlex.quote(f"{resolved}/provenance/w")}' in cmdlines[0]


@pytest.mark.fast
def test_what_the_cli_generates_under_a_search_path_is_not_read_as_a_tool(project: Path,
                                                                          monkeypatch: pytest.MonkeyPatch) -> None:
    """A base path below a search path is generated output, so a second run, and a scan from Python given the
    same base path, find only the tool and the workflow that are there; a base path outside or at a search path is
    no output inside it, and hides nothing."""
    _sophios(monkeypatch, '--generate_cwl_workflow', '--basepath', 'out')
    _sophios(monkeypatch, '--generate_cwl_workflow', '--basepath', 'out')
    assert (project / 'out' / 'w.cwl').is_file()
    config = json.loads((project / 'config.json').read_text(encoding='utf-8'))
    assert [key.stem for key in sophios.plugins.get_tools_cwl(config, basepath='out')] == ['noop']
    assert sorted(sophios.plugins.get_yml_paths(config, basepath=project / 'out')['global']) == ['w']
    assert 'w' in [key.stem for key in sophios.plugins.get_tools_cwl(config)]   # without it, it is read
    for basepath in (project.parent / 'elsewhere', project):
        assert 'w' in [key.stem for key in sophios.plugins.get_tools_cwl(config, basepath=basepath)], basepath


@pytest.mark.fast
@EACH_RUNNER
def test_the_cli_and_python_write_a_run_to_the_same_places(project: Path, monkeypatch: pytest.MonkeyPatch,
                                                           tmp_path: Path, runner: str) -> None:
    """The same workflow run with the same base path leaves its root and job there and a runner command that
    writes provenance, the summary and the outputs there, from `--basepath` and from `run(basepath=)`. The
    command line writes the tree beside the root; Python, one document. `--no_provenance`, and `no_provenance: yes`
    in `run()`'s run arguments, give the runner no `--provenance`; without them it has one."""
    commands: list[str] = []
    monkeypatch.setattr(run_local, 'generate_run_script', commands.append)
    cli_base, python_base = tmp_path / 'cli out', tmp_path / 'python out'
    (project / 'python').mkdir()

    def run(entry: str, base: Path, *no_provenance: str) -> list[str]:
        if entry == 'cli':
            monkeypatch.chdir(project)
            _sophios(monkeypatch, '--generate_run_script', '--cwl_runner', runner, '--basepath', str(base),
                     *no_provenance)
        else:
            monkeypatch.chdir(project / 'python')
            run_args = {'generate_run_script': 'yes', 'cwl_runner': runner}
            if no_provenance:
                run_args['no_provenance'] = 'yes'
            Workflow([Step(clt_path=project / 'noop.cwl')], 'w').run(basepath=str(base), run_args_dict=run_args)
        return shlex.split(commands[-1])

    for entry, base in (('cli', cli_base), ('python', python_base)):
        words, resolved = run(entry, base), base.resolve()
        assert words[words.index('--provenance') + 1] == f'{resolved}/provenance/w'
        assert words[words.index('--outdir') + 1].startswith(f"{resolved}/outdir_{runner.split('-')[0]}_w_")
        assert runner != 'cwltool' or words[words.index('--write-summary') + 1] == f'{resolved}/output_w.json'
        assert '--provenance' not in run(entry, base, '--no_provenance')
    assert _files(cli_base) == {'w.cwl', 'w_inputs.yml', 'w~noop.cwl'}
    assert _files(python_base) == {'w.cwl', 'w_inputs.yml'}
    assert not (project / 'autogenerated').exists() and not (project / 'python' / 'autogenerated').exists()
