"""The graph Sophios draws: what a document's graph settings and the CLI's `--graphviz` flags do to its DOT source, as
tests/core/data/drawing states it; no image is rendered."""
import re
import shutil
from pathlib import Path
from types import SimpleNamespace
from typing import Any, Final

import pytest
import yaml

from sophios import main

from .cases import DATA, match
from .helpers import no_preflight, run_cli

DRAWING: Final = DATA / 'drawing'
#: A node or edge name in DOT: quoted, or a bare word.
_ID = r'"[^"]*"|\w+'
#: A node or edge statement: its node or its two ends, and its attributes.
_STATEMENT = re.compile(rf'^\s*({_ID})(?: -> ({_ID}))? \[(.*)\]$', re.MULTILINE)
_ATTRIBUTE = re.compile(r'(\w+)=("(?:[^"\\]|\\.)*"|[^\s"]+)')


def _unquoted(text: str) -> str:
    return text[1:-1] if text.startswith('"') else text


def _attributes(text: str) -> dict[str, str]:
    return {key: _unquoted(value) for key, value in _ATTRIBUTE.findall(text)}


def _clusters(dot: str) -> dict[str, dict[str, str]]:
    """Each cluster, with the attributes written before its first node."""
    return {_unquoted(name): _attributes(block) for name, block in
            re.findall(rf'subgraph ({_ID}) {{\n((?:\t+\w+=.*\n)*)', dot)}


@pytest.mark.fast
@pytest.mark.parametrize('drawn', yaml.safe_load((DRAWING / 'expected.yaml').read_text(encoding='utf-8')),
                         ids=lambda drawn: ' '.join(drawn['flags']) or 'default')
def test_the_drawing_is_what_its_example_states(monkeypatch: pytest.MonkeyPatch, tmp_path: Path,
                                                capsys: pytest.CaptureFixture[str], drawn: dict[str, Any]) -> None:
    """`--graphviz` writes `autogenerated/<stem>.wic.gv`: a cluster per workflow, the subworkflows
    `--graph_inline_depth` levels down and no deeper, a box per step labelled with the id the document wrote, or its
    own `wic: graphviz:` label written under its `(index, name)` or its id, `\\n` and all, or with
    `--graph_label_stepname` the generated step name; a step's style after `rounded`; an edge per dependency,
    labelled with the output it carries under `--graph_label_edges`. A subworkflow's own label titles its cluster,
    the calling step's entry wins over it, and without either the cluster is titled with the calling step's id;
    `style: invis` hides the subworkflow, its cluster and the box that calls it, and each call is a cluster of its own.
    A workflow's `ranksame` steps share one rank=same group in its own cluster, and an entry that addresses no step is
    named on stderr, as for a stale `wic: steps:` key."""
    shutil.copytree(DRAWING, tmp_path / 'drawing', ignore=shutil.ignore_patterns('expected.yaml'))
    no_preflight(monkeypatch)
    monkeypatch.setattr(main.shutil, 'which', lambda _name: '/usr/bin/dot')
    monkeypatch.setattr(main, 'sub', SimpleNamespace(run=lambda *_a, **_k: SimpleNamespace(stdout=b'')))
    monkeypatch.chdir(tmp_path / 'drawing')
    assert run_cli(monkeypatch, '--yaml', 'drawn.wic', '--generate_cwl_workflow', '--graphviz', *drawn['flags']) is None
    dot = Path('autogenerated/drawn.wic.gv').read_text(encoding='utf-8')
    statements = [(_unquoted(name), _unquoted(sink), _attributes(attrs))
                  for name, sink, attrs in _STATEMENT.findall(dot)]
    boxes = {name: attrs for name, sink, attrs in statements if not sink}
    edges = [[name, sink, attrs] for name, sink, attrs in statements if sink]
    palette = drawn['palette']
    assert 'bgcolor=transparent\n' in dot and f'fontcolor={palette}\n' in dot
    assert {(attrs['color'], attrs['fontcolor']) for attrs in boxes.values()} == {(palette, palette)}
    assert not any('filled' in attrs['style'] or 'fillcolor' in attrs for attrs in boxes.values())
    clusters = _clusters(dot)
    assert 'clusters' not in drawn or set(clusters) == set(drawn['clusters'])
    assert match(drawn.get('clusters', {}), clusters)
    assert {name: [boxes[name]['label'], boxes[name]['style']] for name in drawn.get('boxes', {})} == drawn.get(
        'boxes', {})
    assert drawn['flags'] or set(boxes) == set(drawn['boxes'])
    assert not [name for name in drawn.get('absent', []) if name in boxes]
    assert 'edges' not in drawn or edges == drawn['edges']
    ranks = [[len(indent), [_unquoted(name) for name in names.split('; ')]]
             for indent, names in re.findall(r'^(\t*)\{rank=same; (.*)\}$', dot, re.MULTILINE)]
    assert 'ranks' not in drawn or ranks == drawn['ranks']
    assert match({'contains': drawn['said']} if 'said' in drawn else {'re': ''}, capsys.readouterr().err)
