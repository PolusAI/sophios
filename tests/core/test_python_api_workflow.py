def _adapter(name: str) -> Path:
    """The path to a packaged CWL adapter, by stem."""
    return ADAPTERS / f"{name}.cwl"


def _emit_text_tool() -> CommandLineTool:
    """A minimal built tool that writes its message to a file."""
    return (
        CommandLineTool(
            "emit_text",
            Inputs(message=Input(cwl.string, position=1)),
            Outputs(file=Output(cwl.file, glob="stdout.txt")),
        )
        .base_command("echo")
        .stdout("stdout.txt")
    )


def _output_directory_tool(path: Path) -> Path:
    """A built tool whose output is a directory it names itself."""
    path.write_text(
        """class: CommandLineTool
cwlVersion: v1.2
requirements:
  InitialWorkDirRequirement:
    listing:
      - entry: $(inputs.outDir)
        writable: true
  InlineJavascriptRequirement: {}
baseCommand: [bash, -lc]
arguments:
  - valueFrom: "touch $(inputs.outDir.basename)/done.txt"
inputs:
  outDir:
    type: Directory
    inputBinding:
      prefix: --outDir
outputs:
  outDir:
    type: Directory
    outputBinding:
      glob: $(inputs.outDir.basename)
""",
        encoding="utf-8",
    )
    return path


