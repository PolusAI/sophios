def _iter_python_workflow_paths(global_config: Json) -> list[tuple[str, Path]]:
    """Every discovered Python workflow, minus the corpora with their own lanes."""
    paths = sophios.plugins.get_workflow_paths(global_config, 'py')
    return [
        (path_str, path)
        for _, paths_dict in paths.items()
        for path_str, path in paths_dict.items()
        if "mm-workflows" not in str(path) and "docs/tutorials/" not in str(path)
    ]


@contextmanager
def _step_registry_injected(tool_registry: Tools) -> Iterator[None]:
    """Inject a default tool registry into imported Python workflow scripts,
    so they see the patched ``Step``."""
    from sophios.api.python import workflow  # pylint: disable=C0415:import-outside-toplevel

    step_class = workflow.Step

    def step_factory(*args: Any, **kwargs: Any) -> Any:
        kwargs.setdefault("tool_registry", tool_registry)
        return step_class(*args, **kwargs)

    with patch.object(workflow, "Step", step_factory):
        yield


def _write_manifest(workflow_paths: list[Path]) -> None:
    """Record the generated `.wic` paths for the validation step that follows."""
    AUTOGENERATED_DIR.mkdir(parents=True, exist_ok=True)
    manifest = sorted({str(path) for path in workflow_paths})
    PYTHON_WORKFLOW_MANIFEST.write_text(
        json.dumps(manifest, indent=2), encoding="utf-8")


@pytest.mark.fast
def test_explicit_ports_and_attribute_sugar_produce_one_document() -> None:
    """`step.inputs.x` and the bare `step.x` sugar are the same binding.

    Both spellings are the Python API's -- this compares them to each other,
    not to the YAML front end. The sugar resolves through `__getattr__`, so it
    is the spelling that can silently diverge.
    """
    touch_legacy = Step(clt_path=_adapter("touch"))
    touch_legacy.filename = "empty.txt"
    append_legacy = Step(clt_path=_adapter("append"))
    append_legacy.file = touch_legacy.file
    append_legacy.str = "Hello"

    touch_explicit = Step(clt_path=_adapter("touch"))
    touch_explicit.inputs.filename = "empty.txt"
    append_explicit = Step(clt_path=_adapter("append"))
    append_explicit.inputs.file = touch_explicit.outputs.file
    append_explicit.inputs.str = "Hello"

    legacy_yaml = Workflow([touch_legacy, append_legacy], "wf").yaml
    explicit_yaml = Workflow([touch_explicit, append_explicit], "wf").yaml

    assert legacy_yaml == explicit_yaml


@pytest.mark.fast
def test_linear_python_workflow_reuses_compiler_edge_inference() -> None:
    """An unbound input is left for inference, not guessed by the API.

    The exported document omits `file` entirely and the compiled one names the
    producing step, so inference ran rather than the API pre-resolving it."""
    touch = Step(clt_path=_adapter("touch"))
    touch.inputs.filename = "empty.txt"

    append = Step(clt_path=_adapter("append"))
    append.inputs.str = "Hello"

    cat = Step(clt_path=_adapter("cat"))

    workflow = Workflow([touch, append, cat], "wf")
    workflow_yaml = workflow.yaml
    assert "file" not in workflow_yaml["steps"][1]["in"]
    assert "file" not in workflow_yaml["steps"][2].get("in", {})

    compiled = workflow.compile()

    assert compiled.cwl_workflow["steps"][1]["in"]["file"] == "wf__step__1__touch/file"
    assert compiled.cwl_workflow["steps"][2]["in"]["file"] == "wf__step__2__append/file"
    assert compiled.cwl_job_inputs == {
        "wf__step__1__touch___filename": "empty.txt",
        "wf__step__2__append___str": "Hello",
    }


