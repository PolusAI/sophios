def _runner_child() -> Iterator[subprocess.Popen[str]]:
    """A process cwltool tracks as a child of its run.

    It exits once its stdin is closed, which is what cwltool does first when it terminates a child.
    """
    child = subprocess.Popen([sys.executable, '-c', 'import sys; sys.stdin.read()'], stdin=subprocess.PIPE, text=True)
    cwltool.utils.processes_to_kill.append(child)
    try:
        yield child
    finally:
        if child in cwltool.utils.processes_to_kill:
            cwltool.utils.processes_to_kill.remove(child)
        child.kill()
        child.wait()


