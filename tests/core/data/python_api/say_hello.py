"""A user's script: it runs a workflow, and prints what its one output holds from the summary the run wrote."""
import json
from pathlib import Path

from sophios.api.python.tool_builder import CommandLineTool, Input, Inputs, Output, Outputs, cwl
from sophios.api.python.workflow import Workflow

echo = (CommandLineTool('echo', Inputs(message=Input(cwl.string, position=1)), Outputs(said=Output.stdout()))
        .base_command('echo').stdout('said.txt').to_step())
echo.inputs.message = 'hello'
Workflow([echo], 'say').run()
summary = json.loads(Path('autogenerated/output_say.json').read_text(encoding='utf-8'))
print(Path(next(iter(summary.values()))['path']).read_text(encoding='utf-8'), end='')
