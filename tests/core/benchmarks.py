# Case 2: speculative insertion.

def _clt(inputs: dict[str, Cwl], outputs: dict[str, Cwl]) -> Cwl:
    """A minimal CommandLineTool stub: `true` succeeds and produces nothing,
    which is all a compile-only registry needs."""
    return {
        'cwlVersion': CWL_VERSION,
        'class': 'CommandLineTool',
        'baseCommand': 'true',
        'inputs': inputs,
        'outputs': outputs,
    }


def _speculative_insertion_registry() -> tuple[Yaml, Tools]:
    """Two branches, each needing exactly one whitelisted-format-converter
    insertion. "Two or more whitelisted converter tools" is the design's own
    phrase for what this path requires (design_docs/core-refactor-design.md
    §6.2). Section 6.3 puts the path in benchmark coverage; §1 documents its
    `O(2^n)` complexity.

    A tool's *input* format must be a single-element list, not a bare string:
    `inference.perform_edge_inference` iterates `in_formats` directly, and
    `utils.flatten` does the same to a whitelist candidate's input formats —
    either given a bare string, the loop walks its characters instead of the
    one format it names, and the whitelist search never fires. This is not
    documented anywhere; it was found by trying the bare-string form first.
    """
    plugin_ns = 'global'
    specs: dict[str, Cwl] = {}
    steps: list[Yaml] = []
    for k in (1, 2):
        src_fmt, dst_fmt = f'edam:format_src{k}', f'edam:format_dst{k}'
        specs[f'mk_{k}'] = _clt(
            {}, {'file': {'type': 'File', 'format': src_fmt, 'outputBinding': {'glob': f'src{k}.txt'}}})
        specs[f'use_{k}'] = _clt(
            {'file': {'type': 'File', 'format': [dst_fmt], 'inputBinding': {'position': 1}}}, {})
        specs[f'insert_steps_automatically_conv_{k}'] = _clt(
            {'file': {'type': 'File', 'format': [src_fmt], 'inputBinding': {'position': 1}}},
            {'file': {'type': 'File', 'format': dst_fmt, 'outputBinding': {'glob': f'dst{k}.txt'}}})
        steps.append({'id': f'mk_{k}', 'in': {}})
        steps.append({'id': f'use_{k}'})
    tools: Tools = {
        StepId(stem, plugin_ns): Tool(f'/synthetic/{stem}.cwl', desugar_into_canonical_normal_form(dict(cwl)))
        for stem, cwl in specs.items()
    }
    return {'steps': steps}, tools


_SPECULATIVE_YML, _SPECULATIVE_TOOLS = _speculative_insertion_registry()


def _run_speculative_insertion() -> None:
    compile_hermetic(_SPECULATIVE_YML, 'oracle', tools=_SPECULATIVE_TOOLS, insert_steps_automatically=True)


# --------------------------------------------------------------------------
# Case 3: deep nesting.

def _deep_nesting_yml() -> Yaml:
    """A leaf step wrapped five levels deep with `hermetic.subworkflow_step`."""
    tree: Yaml = {'steps': [{'id': 'mk_file', 'in': {'name': {'wic_inline_input': 'leaf.txt'}}}]}
    for level in range(5):
        tree = {'steps': [subworkflow_step(f'level_{level}.wic', tree)]}
    return tree


_DEEP_NESTING_YML: Final = _deep_nesting_yml()


# --------------------------------------------------------------------------
# Case 4: wide inference.

def _wide_inference_yml() -> Yaml:
    """One hundred `mk_file` steps, each with its one `name` input left
    unspecified. `name` is a string and every prior output is a `File`, so
    `types_match` never accepts — `perform_edge_inference`'s backward scan
    always runs to completion instead of returning at the first match, which
    is what makes this case pay for the full quadratic scan rather than the
    linear common case."""
    return {'steps': [{'id': 'mk_file'} for _ in range(100)]}


_WIDE_INFERENCE_YML: Final = _wide_inference_yml()


# --------------------------------------------------------------------------
# Case 5: parse only.

def _parse_corpus() -> None:
    for path in CORPUS:
        parse(path.read_text(encoding='utf-8'), filename=path.name)


# --------------------------------------------------------------------------

CASES: Final[tuple[Case, ...]] = tuple(
    Case(f'corpus/{corpus_id(path)}',
         "One of wic_corpus.CORPUS's reachable workflows, compiled for real "
         "against this environment's plugin registry — the trend everyone "
         "actually cares about. Needs a jsonschema validator only because "
         "read_ast_from_disk's signature requires one; it is never called "
         "(ignore_validation_errors=True), which is what keeps this case from "
         "paying for autogenerated/schemas/schema_store.json — building that "
         "store from scratch costs minutes, not milliseconds.",
         run=partial(_compile_corpus_file, path))
    for path in CORPUS
) + (
    Case('speculative_insertion',
         "A workflow with two branches, each needing one whitelisted-format-"
         "converter insertion — the design's own phrase, 'two or more "
         "whitelisted converter tools', for what puts a compilation on this "
         "path. Section 6.3 puts it in benchmark coverage; §1 documents the "
         "O(2^n) complexity. The corpus never reaches it. On "
         "this branch it currently raises on the second fixed-point pass: "
         "insert_step_into_workflow inserts a step with no 'id:' key, which "
         "get_steps_keys requires — a real defect, recorded here rather than "
         "fixed, since Spec 2 does not fix compiler defects it finds.",
         run=_run_speculative_insertion),
    Case('deep_nesting',
         "A workflow partitioned five levels deep with "
         "hermetic.subworkflow_step. Namespacing cost grows with depth and "
         "nothing else on this list has depth.",
         run=lambda: compile_hermetic(_DEEP_NESTING_YML, 'oracle', tools=SYNTHETIC_TOOLS)),
    Case('wide_inference',
         "One hundred steps, every input inferred and never matched, so "
         "perform_edge_inference's backward scan always runs to completion. "
         "It scans backwards over previous steps, so this is the quadratic "
         "one.",
         run=lambda: compile_hermetic(_WIDE_INFERENCE_YML, 'oracle', tools=SYNTHETIC_TOOLS)),
    Case('parse_only',
         "sophios.lang.parse over the corpus, no compilation. Separates a "
         "parser regression from a compiler regression; without it a slow "
         "week has two candidate causes and no way to choose.",
         run=_parse_corpus),
)


def main() -> int:
    """Time every case and print a table. Always returns 0."""
    # Discovery is shared setup, not a property of whichever corpus path sorts
    # first. Keep it lazy when a caller selects only synthetic cases.
    if any(case.name.startswith('corpus/') for case in CASES):
        _get_corpus_env()

    print('| case | seconds |')
    print('|---|---:|')
    corpus_total = 0.0
    all_total = 0.0
    for case in CASES:
        start = time.perf_counter()
        try:
            case.run()
            elapsed_seconds = time.perf_counter() - start
            elapsed = f'{elapsed_seconds:.3f}'
        except Exception as exc:  # pylint: disable=broad-except
            # A case that fails is reported and skipped. This job does not
            # gate, so a broken case must not stop the other numbers arriving.
            elapsed_seconds = time.perf_counter() - start
            elapsed = f'error: {type(exc).__name__}'
        all_total += elapsed_seconds
        if case.name.startswith('corpus/'):
            corpus_total += elapsed_seconds
        print(f'| {case.name} | {elapsed} |')
    print(f'| corpus (total) | {corpus_total:.3f} |')
    print(f'| all cases (total) | {all_total:.3f} |')
    return 0


if __name__ == '__main__':
    sys.exit(main())
