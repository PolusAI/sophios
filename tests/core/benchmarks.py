from sophios.utils_yaml import wic_loader
from sophios.wic_types import Cwl, StepId, Tool, Tools, Yaml, YamlTree


@dataclass(frozen=True, slots=True)
class Case:
    """One thing worth timing, and why it is on the list."""
    name: str
    rationale: str
    run: Callable[[], object]


# --------------------------------------------------------------------------
# Case 1: the corpus, compiled for real.

@dataclass
class _CorpusEnv:
    """The real plugin registry, discovered once and shared by every corpus
    case. Discovering it per file would multiply a filesystem walk
    (`get_tools_cwl` globs `search_paths_cwl`) by the corpus size for no
    benefit — nothing about it varies per file."""
    tools: Tools
    yml_paths: dict[str, dict[str, Path]]
    validator: Draft202012Validator


_corpus_env: _CorpusEnv | None = None


def _get_corpus_env() -> _CorpusEnv:
    """Build (once, lazily) the environment the corpus case compiles against.

    Lazy rather than built at import time: importing this module to run only
    `parse_only` or the synthetic cases should not pay for plugin discovery.

    The validator is a real `Draft202012Validator`, required by
    `read_ast_from_disk`'s signature, but it is constructed against a trivial
    schema and is never invoked — every corpus compile below passes
    `ignore_validation_errors=True`. Building the *real* validator via
    `sophios.schemas.wic_schema.get_validator` writes
    `autogenerated/schemas/schema_store.json`, which is the multi-minute cost
    this module's docstring says to avoid paying weekly for a job that gates
    nothing.
    """
    global _corpus_env  # pylint: disable=global-statement
    if _corpus_env is None:
        args = sophios.cli.get_args()
        config_path = Path(args.config_file)
        config = io.get_config(config_path, config_path) if config_path.exists() else io.get_basic_config()
        tools = sophios.plugins.get_tools_cwl(config, quiet=True)
        yml_paths = sophios.plugins.get_yml_paths(config)
        validator = Draft202012Validator({'type': 'object'})
        _corpus_env = _CorpusEnv(tools, yml_paths, validator)
    return _corpus_env


def _compile_corpus_file(path: Path) -> None:
    """Compile one corpus workflow for real, from disk, against the real
    plugin registry. Mirrors `tests/core/test_examples.py::run_workflows`'s
    compile-only half — the only pattern in this repository for compiling a
    `.wic` file from disk rather than an in-memory dict."""
    env = _get_corpus_env()
    args = sophios.cli.get_args(str(path), ['--ignore_validation_errors'])
    root_yaml_tree: Yaml = yaml.load(path.read_text(encoding='utf-8'), Loader=wic_loader())
    plugin_ns = root_yaml_tree.get('wic', {}).get('namespace', 'global')
    step_id = StepId(path.stem, plugin_ns)
    y_t = YamlTree(step_id, root_yaml_tree)
    yaml_tree_raw = sophios.ast.read_ast_from_disk(
        args.homedir, y_t, env.yml_paths, env.tools, env.validator, args.ignore_validation_errors)
    yaml_tree = sophios.ast.merge_yml_trees(yaml_tree_raw, {}, env.tools)
    root_yml_dir_abs = Path(args.yaml).parent.absolute()
    yaml_tree = sophios.ast.python_script_generate_cwl(yaml_tree, root_yml_dir_abs, env.tools)
    compiler_options, graph_settings, yaml_tag_paths = sophios.cli.get_dicts_for_compilation(args)
    graph = get_graph_reps(str(path))
    sophios.compiler.compile_workflow(
        yaml_tree, compiler_options, graph_settings, yaml_tag_paths,
        [], [graph], {}, {}, {}, {}, env.tools, True, relative_run_path=True, testing=True)


