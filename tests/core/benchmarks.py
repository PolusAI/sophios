"""Compile-cost cases, run weekly and gating nothing.

Not a property suite and not hermetic: the corpus half is the point — a trend
over the workflows people actually compile. It imports `wic_corpus` on purpose
and is excluded from P25's module list for that reason.

There are no thresholds and no assertions. `main` returns 0 whatever the
numbers say. A benchmark that can fail a build is a gate, and the design is
explicit that these are not gates: the guard for correctness is the property
suite, which runs on every change.

The corpus case compiles for real, against the real plugin registry —
`parse_only` deliberately does not, which is what lets a slow week be pinned
to the parser or the compiler instead of leaving two candidate causes and no
way to choose. Real compilation needs a `jsonschema` validator only so that
`sophios.ast.read_ast_from_disk` has one to *call*; it is built here and never
called (`ignore_validation_errors=True`), which is what keeps this module from
paying for `autogenerated/schemas/schema_store.json` on every run — building
that store from scratch costs minutes, and this job is not a gate that anyone
is waiting on.
"""
import sys
import time
from dataclasses import dataclass
from functools import partial
from pathlib import Path
from typing import Callable, Final

import yaml
from jsonschema import Draft202012Validator

# `tests/` has no `__init__.py` (test_hermeticity.py's own comment explains
# why), so a bare `python tests/core/benchmarks.py` runs this file with no
# package context and a relative import would fail immediately. `core/` does
# have one, so the fix is an absolute `core.*` import plus making sure `core`'s
# parent is on `sys.path` — which pytest already does for every other test in
# this package, so this is a no-op under `pytest`. Every import below is
# consequently pushed past the top of the module, hence the blanket disable.
# pylint: disable=wrong-import-position
if __package__ in (None, ''):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from core.hermetic import compile_hermetic, subworkflow_step
from core.synthetic_tools import SYNTHETIC_TOOLS
from core.wic_corpus import CORPUS, corpus_id

import sophios.ast
